/**
 * 本地圖示渲染器，模擬 Lucide.createIcons API
 * 無論連網或離線，100% 渲染所有 [data-lucide]
 */
function renderLocalIcons(options = {}) {
  const root = (options && options.root) ? options.root : document;
  const elements = root.querySelectorAll('[data-lucide]');
  
  elements.forEach(el => {
    const iconName = el.getAttribute('data-lucide');
    const svgPath = SVG_ICONS[iconName];
    if (!svgPath) return;

    if (el.tagName.toLowerCase() === 'svg') {
      // 已經是 SVG，無需重複替換
      return;
    }

    // 保留原本元素上的 class（例如 w-4 h-4 text-indigo-500 等）
    const classes = el.getAttribute('class') || '';

    // 建立 SVG 節點
    const svg = document.createElementNS('http://www.w3.org/2000/svg', 'svg');
    svg.setAttribute('xmlns', 'http://www.w3.org/2000/svg');
    svg.setAttribute('width', '24');
    svg.setAttribute('height', '24');
    svg.setAttribute('viewBox', '0 0 24 24');
    svg.setAttribute('fill', 'none');
    svg.setAttribute('stroke', 'currentColor');
    svg.setAttribute('stroke-width', '2');
    svg.setAttribute('stroke-linecap', 'round');
    svg.setAttribute('stroke-linejoin', 'round');
    svg.setAttribute('class', classes);
    svg.setAttribute('data-lucide', iconName);
    svg.innerHTML = svgPath;

    el.replaceWith(svg);
  });
}

// 掛載到 window 物件，無縫相容任何呼叫
window.lucide = {
  createIcons: renderLocalIcons
};

// DOM 載入時立即執行一次
if (document.readyState === 'loading') {
  document.addEventListener('DOMContentLoaded', () => renderLocalIcons());
} else {
  renderLocalIcons();
}
